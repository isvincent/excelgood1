"""Build videos/<ID>.html (single-file 9:16 autoplay lessons) and js/data.js for the hub.

usage:  python tools/build.py          (run from anywhere)
"""
import hashlib, json, pathlib

TOOLS = pathlib.Path(__file__).parent
ROOT = TOOLS.parent
ORDER = ["XLOOKUP", "UNIQUE", "SORT", "FILTER", "XMATCH", "SORTBY", "LET", "RANDARRAY", "TEXTAFTER",
         "TEXTBEFORE", "TEXTSPLIT", "WRAPCOLS", "WRAPROWS", "TAKE", "CHOOSEROWS", "CHOOSECOLS", "EXPAND",
         "VSTACK", "HSTACK", "VLOOKUP", "SUMPRODUCT", "COUNTIF", "SUMIF", "COUNTA", "INDEX", "MATCH",
         "CONCATENATE", "NETWORKDAYS", "SUBSTITUTE", "SWITCH", "HLOOKUP", "OFFSET", "DATEDIF", "WEEKDAY",
         "TRIM", "LEFT", "RIGHT", "MID", "LEN"]


def wlen(s):
    return sum(0.5 if ord(c) < 128 else 1 for c in s)


def js(o):
    return json.dumps(o, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")


def main():
    tpl = (TOOLS / "player_template.html").read_text(encoding="utf-8")
    lessons = {}
    for i in ORDER:
        p = TOOLS / "lessons" / f"{i}.json"
        if p.exists():
            lessons[i] = json.loads(p.read_text(encoding="utf-8"))
        else:
            print("missing lesson:", i)
    ids = [i for i in ORDER if i in lessons]
    (ROOT / "videos").mkdir(exist_ok=True)
    catalog = []
    for n, i in enumerate(ids):
        L = lessons[i]
        nav = {"prev": ids[n - 1] if n else None, "next": {"id": ids[n + 1]} if n + 1 < len(ids) else None}
        html = (tpl.replace("/*__LESSON__*/null", js(L)).replace("/*__NAV__*/null", js(nav))
                .replace("__ID__", L["id"]).replace("__ZH__", L["zh"]))
        (ROOT / "videos" / f"{i}.html").write_text(html, encoding="utf-8")
        chars = sum(wlen(x) for s in L["slides"] for x in s["say"])
        lines = sum(len(s["say"]) for s in L["slides"])
        secs = round(chars * 0.24 / 1.15 + lines * 0.6 + len(L["slides"]) * 0.8)
        quiz = next((s for s in L["slides"] if s["type"] == "quiz"), None)
        catalog.append({k: L[k] for k in ["id", "cat", "emoji", "zh", "en", "desc", "descEn", "syntax", "keywords", "level", "version"]}
                       | {"slides": len(L["slides"]), "secs": secs,
                          "titles": [s.get("title", L["zh"]) for s in L["slides"]],
                          "quiz": {k: quiz[k] for k in ["q", "options", "answer", "explain"]} if quiz else None})
    (ROOT / "js").mkdir(exist_ok=True)
    (ROOT / "js" / "data.js").write_text("/* generated by tools/build.py */\nwindow.FUNCS = " + json.dumps(catalog, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    # service worker: precache every page so the installed app works offline
    files = ["./", "index.html", "css/style.css", "js/app.js", "js/data.js", "manifest.webmanifest",
             "icons/icon.svg", "icons/icon-192.png", "icons/icon-512.png", "icons/icon-maskable-512.png"]
    files += [f"videos/{i}.html" for i in ids]
    h = hashlib.md5()
    for f in files[1:]:
        h.update((ROOT / f).read_bytes())
    ver = h.hexdigest()[:8]
    sw = (TOOLS / "sw_template.js").read_text(encoding="utf-8").replace("__VER__", ver).replace("__FILES__", json.dumps(files, ensure_ascii=False))
    (ROOT / "sw.js").write_text(sw, encoding="utf-8")
    print(f"built {len(ids)} videos, sw {ver}")


if __name__ == "__main__":
    main()
